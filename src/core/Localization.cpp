const UiStrings& GetStrings() {
    const LANGID langId = GetUserDefaultUILanguage();
    switch (PRIMARYLANGID(langId)) {
        case LANG_JAPANESE: return kJapaneseStrings;
        case LANG_GERMAN:   return kGermanStrings;
        case LANG_FRENCH:   return kFrenchStrings;
        case LANG_SPANISH:  return kSpanishStrings;
        default:            return kEnglishStrings;
    }
}

